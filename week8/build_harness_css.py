#!/usr/bin/env python3
"""Scope videoplay/videoplay.css under .vp so the harness figure can live inside the week 8 page.
:root token blocks are kept global; page-level rules (body, *, .wrap, header, h1, .eyebrow) are dropped.
Writes harness.css next to this file. Rerun after editing videoplay/videoplay.css."""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SKIP = {'*', 'body', '.wrap', 'header.page', '.eyebrow', 'h1', 'h1 em', 'code, pre'}


def blocks(css):
    """Yield (prelude, body) for top-level blocks; @media bodies are returned raw."""
    i, n = 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0:
            break
        prelude = css[i:j].strip()
        depth, k = 1, j + 1
        while depth:
            depth += {'{': 1, '}': -1}.get(css[k], 0)
            k += 1
        yield prelude, css[j + 1:k - 1]
        i = k


def scope(css):
    out = []
    for pre, body in blocks(re.sub(r'/\*.*?\*/', '', css, flags=re.S)):
        if pre.startswith('@media'):
            inner = scope(body)
            if inner.strip():
                out.append(f'{pre} {{\n{inner}}}\n')
        elif pre.startswith(':root'):
            out.append(f'{pre} {{{body}}}\n')
        elif pre in SKIP:
            continue
        else:
            sels = ', '.join('.vp ' + s.strip() for s in pre.split(','))
            out.append(f'{sels} {{{body}}}\n')
    return ''.join(out)


src = (HERE / 'videoplay/videoplay.css').read_text()
(HERE / 'harness.css').write_text('/* Generated by build_harness_css.py from videoplay/videoplay.css. Do not edit by hand. */\n'
                                  + scope(src) + '.vp .lede { margin-top:0; }\n.vp pre, .vp code { font-family:var(--mono); }\n')
print('ok')
